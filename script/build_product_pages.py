#!/usr/bin/env python3
"""
PRADAKO — PRODUCT DETAIL PAGE GENERATOR
=======================================

WHY THIS EXISTS
---------------
Before this, every product's `url` field was empty. 277 products shared exactly
one landing page, which meant:

  - No page could rank for "DIN 933 hex bolt manufacturer India". Competitors
    (Bossard, Wurth, Fastenal) have a page per SKU and take that traffic.
  - There was no URL to paste into an email, an RFQ, or a WhatsApp message.
  - There was no schema.org/Product markup anywhere on the site, so Google had
    nothing structured to read.

This script generates one static page per product from the same catalogue the
gallery uses, so the data can never drift between the two.

    python3 tools/build_product_pages.py

Reads  : js/customised-products-data.js   (generated by build_catalog.py)
Writes : products/<product-id>.html       (277 files)
         products/index.html              (A-Z index of everything)

RUN build_catalog.py FIRST. This script reads its output.

Each page carries:
  - full specification table (standards, cross-reference, drive, head, thread,
    grades, materials, finishes, size range, sectors, testing)
  - schema.org/Product + BreadcrumbList JSON-LD
  - the shared enquiry basket and compare tray
  - deep links into the engineering calculators
  - related products from the same sub-type
  - canonical link and Open Graph tags
"""

import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT_DIR = os.path.join(ROOT, "products")

SITE = "https://www.pradako.co"
CANONICAL_BASE = SITE + "/products/"


def esc(value):
    return (str(value or "")
            .replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace('"', "&quot;"))


def load_catalog():
    """Evaluate the generated JS data file via node and hand back JSON."""
    data_path = os.path.join(ROOT, "js", "customised-products-data.js")
    script = (
        "global.window={};require(%s);"
        "process.stdout.write(JSON.stringify(window.PMEW_CUSTOM_PRODUCT_CATALOG));"
        % json.dumps(data_path)
    )
    raw = subprocess.check_output(["node", "-e", script])
    return json.loads(raw)


