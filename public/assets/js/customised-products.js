    function init() {
        initReveal();
        initCtaForm();

        var section = document.querySelector('.pradako-customised-products-section');
        if (!section || section.dataset.customisedProductsReady === 'true') return;
        section.dataset.customisedProductsReady = 'true';

        buildCatalog();
        if (!catalog.length) return;

        cacheElements(section);
        readUrlState();

        if (window.PradakoList) {
            /* List keeps the preferred procurement selection bar. Its Compare action
               feeds the same window.PradakoCompare store used by all other views. */
            window.PradakoList.mount(el.listBody, el.selectionBar);

            /* The shared List module can redraw itself when photo density/sorting
               changes. Re-apply the selection labels after those internal redraws. */
            if (el.listBody && window.MutationObserver) {
                var listUxFrame = 0;
                new MutationObserver(function () {
                    if (listUxFrame) window.cancelAnimationFrame(listUxFrame);
                    listUxFrame = window.requestAnimationFrame(function () {
                        listUxFrame = 0;
                        enhanceListSelectionUX();
                    });
                }).observe(el.listBody, { childList: true, subtree: true });
            }
        }
        if (window.PradakoCatalogue) {
            window.PradakoCatalogue.mount(el.catalogueHost);
        }

        if (state.query && el.searchInput) el.searchInput.value = state.query;

        bindEvents();
        setView(state.view, true);
    }

