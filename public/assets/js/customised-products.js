    function renderSharedSelectionBar() {
        if (!el.selectionBar || state.view === 'list') return;

        var items = selectedCompareProducts();
        var count = items.length;
        el.selectionBar.classList.toggle('is-visible', count > 0);
        el.selectionBar.setAttribute('aria-hidden', String(count === 0));

        if (!count) {
            el.selectionBar.innerHTML = '';
            return;
        }

        var cart = window.PradakoEnquiryCart;
        var room = cart ? Math.max(0, cart.MAX - cart.count()) : count;
        var addable = Math.min(count, room);
        var compareReady = count >= 2;

        el.selectionBar.innerHTML =
            '<span class="pmew-selbar-count"><strong>' + count + '</strong> selected</span>' +
            '<button type="button" class="pmew-selbar-primary" data-add-compare-selection' +
            (addable <= 0 ? ' disabled' : '') + '>' + icon('plus') +
            '<span>Add ' + (addable > 0 ? addable : count) + ' to Enquiry</span></button>' +
            '<button type="button" class="pmew-selbar-secondary" data-open-shared-compare' +
            (compareReady ? '' : ' disabled') + '>' + icon('compare') +
            '<span>' + (compareReady ? 'Compare' : 'Select 1 more') + '</span></button>' +
            '<button type="button" class="pmew-selbar-clear" data-clear-shared-compare>Clear</button>';
    }

    function addCompareSelectionToEnquiry() {
        var cart = window.PradakoEnquiryCart;
        var items = selectedCompareProducts();
        if (!cart || !items.length) return;

        var added = 0, skipped = 0;
        items.forEach(function (product) {
            if (cart.has(product.id) || cart.isFull()) { skipped += 1; return; }
            if (cart.add({
                id: product.id,
                partNo: product.partNo,
                name: product.name,
                category: product.category || product.subType,
                family: product.family,
                familyUrl: product.familyUrl,
                image: product.image
            }, true)) added += 1;
            else skipped += 1;
        });

        if (added && skipped) {
            cart.toast(added + ' added, ' + skipped + ' skipped — the enquiry basket holds ' +
                cart.MAX + ' products.', 'warning');
        } else if (added) {
            cart.toast(added + ' product' + (added === 1 ? '' : 's') +
                ' added to your enquiry.', 'success');
        } else {
            cart.toast('These products are already in the enquiry basket, or the basket is full.', 'warning');
        }
        renderSharedSelectionBar();
    }

