    function initReveal() {
        if (window.__pmewRevealReady) return;
        window.__pmewRevealReady = true;

        var selector = '.pradako-products-section-title,.pmew-cta-band';
        var reduced = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

        if (reduced || !('IntersectionObserver' in window)) {
            document.querySelectorAll(selector).forEach(function (n) {
                n.classList.add('pmew-page-visible');
            });
            return;
        }

        var observer = new window.IntersectionObserver(function (entries) {
            entries.forEach(function (entry) {
                if (!entry.isIntersecting) return;
                entry.target.classList.add('pmew-page-visible');
                observer.unobserve(entry.target);
            });
        }, { threshold: 0.08, rootMargin: '0px 0px -60px 0px' });

        var prepare = function () {
            document.querySelectorAll(selector).forEach(function (node) {
                if (node.dataset.pmewAnimated === 'true') return;
                node.dataset.pmewAnimated = 'true';
                node.classList.add('pmew-page-animate');
                observer.observe(node);
            });
        };

        prepare();
        new window.MutationObserver(prepare).observe(document.body, { childList: true, subtree: true });

        window.setInterval(function () {
            document.querySelectorAll('.pmew-page-animate:not(.pmew-page-visible)').forEach(function (node) {
                if (node.getBoundingClientRect().top < window.innerHeight * 1.6) {
                    node.classList.add('pmew-reveal-failsafe');
                }
            });
        }, 3000);
    }

