    function bindEvents() {
        if (el.galleryBtn) el.galleryBtn.addEventListener('click', function () { setView('gallery'); });
        if (el.gridBtn) el.gridBtn.addEventListener('click', function () { setView('grid'); });
        if (el.listBtn) el.listBtn.addEventListener('click', function () { setView('list'); });
        if (el.detailsBtn) el.detailsBtn.addEventListener('click', function () { setView('detail'); });
        if (el.chartBtn) el.chartBtn.addEventListener('click', function () { setView('chart'); });

        /* Observation 1: one search box, every view. */
        if (el.searchInput) {
            var debounce = null;
            el.searchInput.addEventListener('input', function () {
                window.clearTimeout(debounce);
                debounce = window.setTimeout(function () {
                    state.query = normalise(el.searchInput.value);
                    if (state.view === 'grid' && state.query) setView('gallery');
                    else refresh();
                }, 180);
            });
            el.searchInput.addEventListener('keydown', function (event) {
                if (event.key === 'Escape') {
                    el.searchInput.value = ''; state.query = ''; refresh();
                }
                if (event.key === 'Enter') {
                    event.preventDefault();
                    window.clearTimeout(debounce);
                    state.query = normalise(el.searchInput.value);
                    if (state.view === 'grid' && state.query) setView('gallery');
                    else refresh();
                }
            });
        }

        if (el.clearAll) {
            el.clearAll.addEventListener('click', function () {
                state.query = '';
                state.facets = {};
                state.family = 'all';
                state.subType = 'all';
                state.category = 'all';
                if (el.searchInput) el.searchInput.value = '';
                refresh();
            });
        }

        if (el.facetToggle) {
            el.facetToggle.addEventListener('click', function () {
                state.facetsOpen = !state.facetsOpen;
                el.section.classList.toggle('pmew-facets-open', state.facetsOpen);
                el.facetToggle.setAttribute('aria-expanded', String(state.facetsOpen));
            });
        }

        if (el.facetPanel) {
            el.facetPanel.addEventListener('change', function (event) {
                var key = event.target.getAttribute('data-facet');
                if (!key) return;

                var list = (state.facets[key] || []).slice();
                var value = event.target.value;

                if (event.target.checked) { if (list.indexOf(value) < 0) list.push(value); }
                else list = list.filter(function (v) { return v !== value; });

                state.facets[key] = list;
                if (state.view === 'grid') setView('gallery');
                else refresh();
            });

            el.facetPanel.addEventListener('click', function (event) {
                var more = event.target.closest('[data-facet-more]');
                if (more) {
                    var rest = more.previousElementSibling;
                    if (rest) { rest.classList.remove('pmew-is-collapsed'); more.remove(); }
                    return;
                }
                if (event.target.closest('[data-facet-reset]')) { state.facets = {}; refresh(); }
            });
        }

        if (el.detailsSort) {
            el.detailsSort.addEventListener('change', function () {
                state.detailsSort = el.detailsSort.value;
                renderDetails();
            });
        }

        /* One delegated handler for tabs, drill-down, chart and compare. */
        el.section.addEventListener('click', function (event) {
            var target;

            if ((target = event.target.closest('[data-clear-active-filters]'))) {
                state.query = '';
                state.facets = {};
                state.family = 'all';
                state.subType = 'all';
                state.category = 'all';
                if (el.searchInput) el.searchInput.value = '';
                refresh();
                return;
            }

            if ((target = event.target.closest('[data-remove-active-filter]'))) {
                var filterType = target.getAttribute('data-remove-active-filter');

                if (filterType === 'query') {
                    state.query = '';
                    if (el.searchInput) el.searchInput.value = '';
                } else if (filterType === 'family') {
                    state.family = 'all';
                    state.subType = 'all';
                    state.category = 'all';
                } else if (filterType === 'subtype') {
                    state.subType = 'all';
                    state.category = 'all';
                } else if (filterType === 'category') {
                    state.category = 'all';
                } else if (filterType === 'facet') {
                    var facetKey = target.getAttribute('data-filter-key');
                    var facetValue = target.getAttribute('data-filter-value');
                    state.facets[facetKey] = (state.facets[facetKey] || []).filter(function (value) {
                        return value !== facetValue;
                    });
                }

                refresh();
                return;
            }

            /* Chart: add an entire type column in one action. */
            if ((target = event.target.closest('[data-add-group]'))) {
                var chartKey = target.getAttribute('data-add-group');
                var cart = window.PradakoEnquiryCart;
                if (!cart) return;

                var added = 0, skipped = 0;
                filtered().forEach(function (product) {
                    if (product.groupKey !== chartKey) return;
                    if (cart.has(product.id) || cart.isFull()) { skipped += 1; return; }
                    if (cart.add({
                        id: product.id,
                        partNo: product.partNo, name: product.name,
                        category: product.category || product.subType,
                        family: product.family, familyUrl: product.familyUrl,
                        image: product.image
                    }, true)) added += 1;
                    else skipped += 1;
                });

                if (added && skipped) {
                    cart.toast(added + ' added, ' + skipped + ' skipped \u2014 the basket holds ' +
                        cart.MAX + ' products.', 'warning');
                } else if (added) {
                    cart.toast(added + ' product' + (added === 1 ? '' : 's') +
                        ' added to your enquiry.', 'success');
                } else {
                    cart.toast('Nothing added \u2014 already in the basket, or it is full.', 'error');
                }

                renderChart();
                return;
            }



            if ((target = event.target.closest('[data-add-compare-selection]'))) {
                event.preventDefault();
                addCompareSelectionToEnquiry();
                return;
            }

            if ((target = event.target.closest('[data-open-shared-compare]'))) {
                event.preventDefault();
                if (!window.PradakoCompare || window.PradakoCompare.count() < 2) return;
                window.PradakoCompare.open();
                return;
            }

            if ((target = event.target.closest('[data-clear-shared-compare]'))) {
                event.preventDefault();
                if (window.PradakoCompare && typeof window.PradakoCompare.clear === 'function') {
                    window.PradakoCompare.clear();
                } else if (window.PradakoCompare) {
                    window.PradakoCompare.items().slice().forEach(function (product) {
                        window.PradakoCompare.remove(product.id);
                    });
                }
                syncCompareButtons();
                renderSharedSelectionBar();
                return;
            }

            if ((target = event.target.closest('[data-compare-id]'))) {
                if (!window.PradakoCompare) return;
                var cid = target.getAttribute('data-compare-id');

                if (window.PradakoCompare.has(cid)) window.PradakoCompare.remove(cid);
                else {
                    var prod = productById(cid);
                    if (prod) window.PradakoCompare.add(prod);
                }

                /* Update this one button in place. Re-rendering the whole grid
                   here detached the card the user had just clicked and threw
                   away their scroll position. */
                syncCompareButtons();
                renderSharedSelectionBar();
                return;
            }

            if ((target = event.target.closest('[data-gallery-size]'))) {
                var requestedSize = target.getAttribute('data-gallery-size');
                if (['small', 'medium', 'large'].indexOf(requestedSize) > -1) {
                    state.gallerySize = requestedSize;
                    renderGallery();
                    writeUrlState();
                }
                return;
            }

            if ((target = event.target.closest('[data-detail-expand]'))) {
                var card = target.closest('.pmew-detail-card');
                var more = card && card.querySelector('.pmew-detail-more');
                if (!more) return;
                var open = more.hidden;
                more.hidden = !open;
                target.textContent = open
                    ? 'Hide technical specification'
                    : 'Expand technical specification';
                target.classList.toggle('is-open', open);
                return;
            }

            if ((target = event.target.closest('[data-showmore]'))) {
                var which = target.getAttribute('data-showmore');
                if (which === 'details') state.detailsExpanded = !state.detailsExpanded;
                if (which === 'chart') state.chartExpanded = !state.chartExpanded;
                renderCurrent();
                return;
            }

            if ((target = event.target.closest('[data-subtype]'))) {
                state.subType = target.getAttribute('data-subtype');
                state.category = 'all';
                refresh();
                return;
            }

            if ((target = event.target.closest('[data-category]'))) {
                state.category = target.getAttribute('data-category');
                refresh();
                return;
            }

            if ((target = event.target.closest('[data-family]'))) {
                state.family = target.getAttribute('data-family');
                state.subType = 'all';
                state.category = 'all';
                if (state.view === 'grid') setView('gallery');
                else refresh();
                return;
            }

            if ((target = event.target.closest('[data-custom-breadcrumb-action]'))) {
                var action = target.getAttribute('data-custom-breadcrumb-action');

                if (action === 'root') {
                    state.family = 'all'; state.subType = 'all'; state.category = 'all';
                    state.query = ''; state.facets = {};
                    if (el.searchInput) el.searchInput.value = '';
                    setView('gallery');
                    return;
                }
                if (action === 'view') { state.family = 'all'; state.subType = 'all'; state.category = 'all'; }
                if (action === 'family') { state.subType = 'all'; state.category = 'all'; }
                if (action === 'subtype') { state.category = 'all'; }
                if (action === 'query') { state.query = ''; if (el.searchInput) el.searchInput.value = ''; }
                refresh();
            }
        });

        if (window.PradakoEnquiryCart) {
            window.PradakoEnquiryCart.on('change', function () {
                document.querySelectorAll('[data-cart-badge]').forEach(function (node) {
                    node.textContent = window.PradakoEnquiryCart.count() + '/' + window.PradakoEnquiryCart.MAX;
                });
                if (state.view === 'chart') renderChart();
                renderSharedSelectionBar();
            });
        }

        if (window.PradakoCompare) {
            window.PradakoCompare.on('change', function () {
                syncCompareButtons();
                renderSharedSelectionBar();
            });
        }

        window.addEventListener('resize', renderFamilyTabs, { passive: true });

        window.addEventListener('popstate', function () {
            state.view = 'gallery';
            state.family = 'all';
            state.subType = 'all';
            state.category = 'all';
            state.query = '';
            state.facets = {};
            state.detailsExpanded = false;
            state.chartExpanded = false;
            readUrlState();
            if (el.searchInput) el.searchInput.value = state.query;
            setView(state.view, true);
        });
    }

    /* In-place refresh of every Compare control, avoiding a full re-render. */
    function syncCompareButtons() {
        if (!window.PradakoCompare) return;

        document.querySelectorAll('[data-compare-id]').forEach(function (button) {
            var product = productById(button.getAttribute('data-compare-id'));
            var selected = window.PradakoCompare.has(button.getAttribute('data-compare-id'));
            button.classList.toggle('is-added', selected);
            button.setAttribute('aria-pressed', String(selected));
            button.setAttribute('title', selected ? 'Remove from comparison' : 'Select for comparison');
            if (product) {
                button.setAttribute('aria-label', (selected ? 'Remove ' : 'Select ') + product.name +
                    (selected ? ' from comparison' : ' for comparison'));
            }
            var label = button.querySelector('[data-compare-label]');
            if (label) {
                label.textContent = button.classList.contains('pmew-card-compare')
                    ? (selected ? 'Selected' : 'Compare')
                    : (selected ? 'Selected for comparison' : 'Select for comparison');
            }
        });
    }

