    function sortProducts(list) {
        var sorted = list.slice();
        if (state.detailsSort === 'name') {
            sorted.sort(function (a, b) { return a.name.localeCompare(b.name); });
        } else if (state.detailsSort === 'type') {
            sorted.sort(function (a, b) {
                return a.subType.localeCompare(b.subType) || a.name.localeCompare(b.name);
            });
        } else if (state.detailsSort === 'standard') {
            sorted.sort(function (a, b) {
                var sa = ((a.attributes.standards || [])[0] || '');
                var sb = ((b.attributes.standards || [])[0] || '');
                return sa.localeCompare(sb) || a.name.localeCompare(b.name);
            });
        }
        return sorted;
    }

