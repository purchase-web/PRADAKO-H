    function enhanceListSelectionUX() {
        if (!el.listBody) return;

        var table = el.listBody.querySelector('table');
        if (!table) return;

        var headCheckbox = table.querySelector('thead input[type="checkbox"]');
        if (headCheckbox) {
            headCheckbox.setAttribute('aria-label', 'Select all visible products');
            headCheckbox.setAttribute('title', 'Select all visible products');

            var headingCell = headCheckbox.closest('th');
            if (headingCell) {
                headingCell.classList.add('pmew-list-select-heading-cell');

                if (!headingCell.querySelector('.pmew-list-select-heading-label')) {
                    var headingWrap = document.createElement('label');
                    headingWrap.className = 'pmew-list-select-heading-label';
                    headingWrap.setAttribute('title', 'Select or clear all visible products');

                    var parent = headCheckbox.parentNode;
                    parent.insertBefore(headingWrap, headCheckbox);
                    headingWrap.appendChild(headCheckbox);

                    var headingText = document.createElement('span');
                    headingText.textContent = 'SELECT';
                    headingWrap.appendChild(headingText);
                }
            }
        }

        Array.prototype.forEach.call(table.querySelectorAll('tbody tr'), function (row) {
            var checkbox = row.querySelector('input[type="checkbox"]');
            if (!checkbox) return;

            var productName = '';
            var namedCell = row.querySelector('[data-product-name], .pmew-list-product-name, .product-name');
            if (namedCell) productName = clean(namedCell.textContent);
            if (!productName) {
                var cells = row.querySelectorAll('td');
                if (cells.length > 2) productName = clean(cells[2].textContent);
            }
            productName = productName || 'this product';

            checkbox.setAttribute('aria-label', 'Select ' + productName + ' for enquiry or comparison actions');
            checkbox.setAttribute('title', 'Select ' + productName + ' for enquiry or comparison actions');

            var cell = checkbox.closest('td');
            if (cell) cell.classList.add('pmew-list-select-cell');
        });
    }

